def to_bytes(rows):
    out = []
    for row in rows:
        row = row.replace('.', '0').replace('#', '1')
        row = row.ljust(8, '0')
        assert len(row) == 8, f"row must be 8 chars, got {len(row)}: {rows}"
        out.append(int(row, 2))
    return out


def main():
    lines = []
    lines.append("// Generated by tools/make_font.py. 8x8 1bpp font, indexed by ASCII - 32.")
    lines.append("#ifndef _FONT8X8_H")
    lines.append("#define _FONT8X8_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("// 8 bytes per glyph, 8 rows of 8 bits (MSB = left).")
    lines.append("// Index = c - 32. Unlisted glyphs are blank.")
    lines.append("static const uint8_t font8x8[][8] = {")
    for i in range(32, 127):
        c = chr(i)
        if c in GLYPHS:
            bytes_out = to_bytes(GLYPHS[c])
            lines.append("    {" + ",".join(f"0x{b:02X}" for b in bytes_out) + "}, // '" + c + "'")
        else:
            lines.append("    {0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00},")
    lines.append("};")
    lines.append("#endif")
    with open("src/font8x8.h", "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Generated src/font8x8.h with {len([c for c in range(32,127) if chr(c) in GLYPHS])} glyphs")


if __name__ == "__main__":
    main()
